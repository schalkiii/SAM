#!/system/bin/sh
# 把 etc/hosts 转成 AdGuardHome 本地过滤器规则
# 目的: 保留 GitHub/FCM/ROM 域名覆盖能力，但不再 bind-mount /system/etc/hosts

source "/data/adb/modules/SAM/scripts/base.sh"

hosts_filter_changed=0
agh_conf_changed=0

hosts_filter_header(){
    printf '%s\n' "! SAM Hosts DNS rewrite"
    printf '%s\n' "! Generated by scripts/update/agh_hosts.sh. Do not edit manually."
}

# 严格解析 "IP 域名..."，跳过 localhost/系统保留域
# 多条同域规则会被 AGH 合并成多个 A/AAAA 响应，和 hosts 多 IP 行为接近
hosts_generate_rules(){
    [ -f "${HOSTS_FILE}" ] || return 0
    awk '
        function valid_ipv4(ip,    parts, n, i) {
            n = split(ip, parts, ".")
            if (n != 4) return 0
            for (i = 1; i <= 4; i++) {
                if (parts[i] !~ /^[0-9]+$/) return 0
                if (parts[i] + 0 > 255) return 0
            }
            return 1
        }
        function valid_ipv6(ip) {
            return ip ~ /^[0-9A-Fa-f:.]+$/ && ip ~ /:/
        }
        function valid_domain(domain) {
            return domain ~ /^[A-Za-z0-9._-]+$/
        }
        function skipped_domain(domain,    lower) {
            lower = tolower(domain)
            if (lower == "localhost" || lower == "ip6-localhost" || lower == "ip6-loopback" || lower == "broadcasthost") return 1
            if (lower ~ /\.local$/ || lower ~ /\.localdomain$/ || lower ~ /\.arpa$/) return 1
            return 0
        }
        {
            sub(/#.*/, "")
            if (NF < 2) next
            ip = $1
            if (valid_ipv4(ip)) rr_type = "A"
            else if (valid_ipv6(ip)) rr_type = "AAAA"
            else next
            for (i = 2; i <= NF; i++) {
                domain = $i
                sub(/\.$/, "", domain)
                if (!valid_domain(domain) || skipped_domain(domain)) continue
                printf "||%s^$dnsrewrite=NOERROR;%s;%s\n", domain, rr_type, ip
            }
        }
    ' "${HOSTS_FILE}" 2>/dev/null | sort -u
}

write_filter_file(){
    mkdir -p "${HOSTS_FILTER_DIR}" "${TMP_PATH}" 2>/dev/null
    filter_tmp="${TMP_PATH}/sam-hosts.txt.$$"
    {
        hosts_filter_header
        hosts_generate_rules
    } > "${filter_tmp}" 2>/dev/null || {
        rm -f "${filter_tmp}"
        return 1
    }

    if [ ! -f "${HOSTS_FILTER_FILE}" ] || ! cmp -s "${filter_tmp}" "${HOSTS_FILTER_FILE}"; then
        mv -f "${filter_tmp}" "${HOSTS_FILTER_FILE}" || {
            rm -f "${filter_tmp}"
            return 1
        }
        hosts_filter_changed=1
    else
        rm -f "${filter_tmp}"
    fi
}

clear_filter_file(){
    mkdir -p "${HOSTS_FILTER_DIR}" "${TMP_PATH}" 2>/dev/null
    filter_tmp="${TMP_PATH}/sam-hosts-empty.$$"
    hosts_filter_header > "${filter_tmp}" 2>/dev/null || {
        rm -f "${filter_tmp}"
        return 1
    }

    if [ ! -f "${HOSTS_FILTER_FILE}" ] || ! cmp -s "${filter_tmp}" "${HOSTS_FILTER_FILE}"; then
        mv -f "${filter_tmp}" "${HOSTS_FILTER_FILE}" || {
            rm -f "${filter_tmp}"
            return 1
        }
        hosts_filter_changed=1
    else
        rm -f "${filter_tmp}"
    fi
}

# 在 AGH 的 filters 段中确保本地过滤器条目存在
# 只追加一次，不覆盖用户自己的过滤器
ensure_filter_entry(){
    sanitize_config "${AGH_CONF}"
    if [ $? -eq 2 ]; then
        log "e" "AdGuardHome 配置是 UTF-16，无法写入 Hosts 过滤器条目"
        return 1
    fi
    [ -f "${AGH_CONF}" ] || {
        log "e" "AdGuardHome 配置不存在，无法写入 Hosts 过滤器条目"
        return 1
    }

    conf_tmp="${TMP_PATH}/agh_hosts_conf.$$"
    awk -v marker="${HOSTS_FILTER_FILE}" -v filter_name="${HOSTS_FILTER_NAME}" -v filter_id="${HOSTS_FILTER_ID}" '
        BEGIN { in_filters = 0; found = 0 }
        /^filters:$/ {
            in_filters = 1
            print
            next
        }
        in_filters && /^[^[:space:]]/ {
            if (!found) {
                printf "  - enabled: true\n    url: %s\n    name: %s\n    id: %s\n", marker, filter_name, filter_id
                found = 1
            }
            in_filters = 0
        }
        in_filters && index($0, "url: " marker) > 0 {
            found = 1
        }
        { print }
        END {
            if (in_filters && !found) {
                printf "  - enabled: true\n    url: %s\n    name: %s\n    id: %s\n", marker, filter_name, filter_id
            }
        }
    ' "${AGH_CONF}" > "${conf_tmp}" 2>/dev/null || {
        rm -f "${conf_tmp}"
        return 1
    }

    if [ ! -s "${conf_tmp}" ] || ! grep -q '^dns:' "${conf_tmp}" || ! grep -q '^filters:' "${conf_tmp}"; then
        log "e" "写入 Hosts 过滤器条目后的 AGH 配置校验失败，保留原文件"
        rm -f "${conf_tmp}"
        return 1
    fi

    if cmp -s "${conf_tmp}" "${AGH_CONF}"; then
        rm -f "${conf_tmp}"
    else
        mv -f "${conf_tmp}" "${AGH_CONF}" || {
            rm -f "${conf_tmp}"
            return 1
        }
        agh_conf_changed=1
    fi
}

reload_agh_if_changed(){
    [ "${hosts_filter_changed}" = "1" ] || [ "${agh_conf_changed}" = "1" ] || return 0
    [ "${AGH_ENABLE}" = "true" ] || return 0
    isRun "${AGH_BIN}" || return 0

    log "i" "重启 AdGuardHome 以加载 Hosts DNS 重写"
    sh "${SERVICE_PATH}/agh.sh" stop > /dev/null 2>&1
    sh "${SERVICE_PATH}/agh.sh" start
}

sync_hosts_filter(){
    hosts_filter_changed=0
    agh_conf_changed=0
    write_filter_file || return 1
    ensure_filter_entry || return 1
    reload_agh_if_changed
}

clear_hosts_filter(){
    hosts_filter_changed=0
    agh_conf_changed=0
    clear_filter_file || return 1
    reload_agh_if_changed
}

case "$1" in
    sync)
        sync_hosts_filter
        ;;
    clear)
        clear_hosts_filter
        ;;
    *)
        echo "使用: sync(从 etc/hosts 生成 AGH 过滤器) | clear(清空过滤器规则)"
        exit 1
        ;;
esac
